import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TABLE = ROOT / 'out' / 'client_catalogs' / 'tables'

def load(name):
    return json.loads((TABLE / (name + '.json')).read_text(encoding='utf-8'))['数据']

def rows(name):
    data = load(name)
    if '键值条目' in data:
        return [x['值'] for x in data['键值条目']]
    out=[]
    for v in data.values():
        if isinstance(v, dict): out.append(v)
    return out

random = load('cards_random')
pool_rows = rows('cards_pool')
cards = load('cards')
promise = load('cards_promise_rule')
prob = rows('cards_prob')
level_exp = load('cards_level_exp')
rarity = load('cards_rarity')
bonus = load('bonus')
dungeons = load('dungeons')

pool = {1: [], 3: []}
for r in pool_rows:
    if r.get('pool_id') in pool:
        cid = int(r['card_id'])
        c = cards.get(str(cid), {})
        pool[r['pool_id']].append((cid, int(r.get('card_group') or 0), int(c.get('rarity') or 0)))
if not pool[3]:
    # cards_random 3 explicitly points to pool_id 1; the member table uses
    # that shared pool key rather than duplicating rows.
    pool[3] = list(pool[1])

prob_map={}
for r in prob:
    if int(r.get('_id',0)) == 1001:
        prob_map[int(r['count'])] = [(int(x[0]), int(x[1])) for x in r.get('group_weights', [])]

def go_slice(items):
    return ','.join('{%d,%d,%d}' % x for x in items)
def go_weights(items):
    return ','.join('{%d,%d}' % x for x in items)

out = '''package game

// Code generated by out/tools/generate_gacha_catalog.py from verified
// Android 1.0.128 tables. Do not edit by hand.
type gachaCardEntry struct { CardID, Group, Rarity int }
type gachaWeight struct { Group, Weight int }
type gachaPoolConfig struct { PoolID, CostMaterial, CostCount, LimitCount, GuaranteeRarity int; ProbabilityID int; Cards []gachaCardEntry; Weights map[int][]gachaWeight }

var androidGachaPools = map[int]gachaPoolConfig{
'''
for pid in (1,3):
    cfg=random[str(pid)]
    out += '\t%d: {PoolID:%d, CostMaterial:%d, CostCount:%d, LimitCount:%d, GuaranteeRarity:%d, ProbabilityID:%d, Cards:[]gachaCardEntry{%s}, Weights:map[int][]gachaWeight{\n' % (pid,pid,cfg['consume_material'][0],cfg['consume_material'][1],int(cfg.get('limit_count') or 0),int(cfg.get('guarantee_rarity') or 0),cfg['prob_id'],go_slice(pool[pid]))
    for count, weights in sorted(prob_map.items()):
        out += '\t\t%d: []gachaWeight{%s},\n' % (count, go_weights(weights))
    out += '\t},},\n'
out += '}\n\nvar androidFirstDrawCardID = 3202\nvar androidFirstDrawRuleID = 1001\nvar androidFirstDrawBonusMaterial = 521\nvar androidFirstDrawBonusCount int64 = 1\n'
out += '\nvar androidMainlineRewards = map[int]map[int]int{\n'
for k,d in dungeons.items():
    if not isinstance(d,dict) or d.get('dungeon_type') != 1 or not d.get('first_bonus'): continue
    b=bonus.get(str(d['first_bonus']),{})
    items=b.get('fixed_items') or []
    if not items: continue
    out += '\t%d: map[int]int{' % int(k)
    for item in items:
        out += '%d:%d,' % (int(item[0]),int(item[1]))
    out += '},\n'
out += '}\n'
out += '\nvar androidCardLevelExp = map[int]int{\n'
for k,v in level_exp.items():
    if isinstance(v,dict) and str(k).isdigit() and v.get('level_max_exp') is not None:
        out += '\t%d:%d,\n' % (int(k),int(v['level_max_exp']))
out += '}\nvar androidRarityUpgradeCost = map[int][2]int{\n'
for k,v in rarity.items():
    if isinstance(v,dict) and isinstance(v.get('consume_materials'),list) and len(v['consume_materials'])==2:
        out += '\t%d:{%d,%d},\n' % (int(k),int(v['consume_materials'][0]),int(v['consume_materials'][1]))
out += '}\n'
(ROOT/'internal'/'game'/'gacha_catalog_generated.go').write_text(out,encoding='utf-8')
print('generated', len(out), 'bytes')
