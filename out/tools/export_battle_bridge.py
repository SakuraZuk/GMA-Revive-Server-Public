# -*- coding: utf-8 -*-
"""更新现行战斗桥的版本头和摘要。内嵌脚本为维护源，不能被旧参考覆盖。"""
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.stdout.reconfigure(encoding='utf-8')


HEADER = '''# REVIVAL_BATTLE_BRIDGE (generated by out/tools/export_battle_bridge.py)
# 来源: GMA-Revive-Server turnclock.client_bridge_source()，现行修复维护于本文件
# bridge_version=%d bridge_revision=%d hotfix_index=%d
# sha256=%s
'''


def main():
    target = ROOT / 'internal/game/battle_bridge_script.py'
    existing = target.read_text(encoding='utf-8')
    if not existing.startswith('# REVIVAL_BATTLE_BRIDGE'):
        raise RuntimeError('现行战斗桥缺少来源边界，拒绝覆盖')
    source = existing.split('\n', 4)[4]
    index = int(re.search(r'bridgeHotfixIndex\s*=\s*(\d+)',
        (ROOT / 'internal/game/battle_observe.go').read_text(encoding='utf-8')).group(1))
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    header = HEADER % (1, 15, index, digest)
    target.write_text(header + source, encoding='utf-8')
    print('生成 %s %d 字节 sha256=%s' % (target.relative_to(ROOT), len(source), digest))


if __name__ == '__main__':
    main()
