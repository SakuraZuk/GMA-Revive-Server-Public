# -*- coding: utf-8 -*-
"""从参考项目 turnclock.py 导出客户端战斗观察桥脚本，固化为 Go 内嵌资源。

产出 internal/game/battle_bridge_script.py（Python2 客户端脚本原文，原样下发，
不修改内容）。来源：GMA-Revive-Server turnclock.client_bridge_source()，
bridge revision 15 / 握手协议版本 1 / 热修索引 2026100816。
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / '_ref' / 'GMA-Revive-Server-main'
sys.path.insert(0, str(REF))
sys.stdout.reconfigure(encoding='utf-8')

import turnclock  # noqa: E402

HEADER = '''# REVIVAL_BATTLE_BRIDGE (generated by out/tools/export_battle_bridge.py)
# 来源: GMA-Revive-Server turnclock.client_bridge_source()
# bridge_version=%d bridge_revision=%d hotfix_index=%d
# sha256=%s
'''


def main():
    source = turnclock.client_bridge_source()
    digest = hashlib.sha256(source.encode('utf-8')).hexdigest()
    header = HEADER % (turnclock.BRIDGE_VERSION, turnclock.BRIDGE_REVISION,
                       turnclock.BRIDGE_HOTFIX_INDEX, digest)
    target = ROOT / 'internal/game/battle_bridge_script.py'
    target.write_text(header + source, encoding='utf-8')
    print('生成 %s %d 字节 sha256=%s' % (target.relative_to(ROOT), len(source), digest))


if __name__ == '__main__':
    main()
